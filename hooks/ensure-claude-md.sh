#!/bin/bash
# SessionStart hook: гарантирует, что в рабочей папке сессии есть CLAUDE.md.
#
# Зачем: 22.09.2026 Claude Code удалил jsonl шести сессий по cleanupPeriodDays —
# переписка пропала, уцелело только то, что лежало в папках проектов. CLAUDE.md
# автозагружается при каждом старте и переживает потерю переписки, поэтому он
# должен быть в каждой рабочей папке, а не только там, где о нём вспомнили.
#
# Что делает: если в cwd нет CLAUDE.md — создаёт скелет. Ничего не перезаписывает.
# Пропускает служебные каталоги, где такой файл не нужен.

set -uo pipefail

INPUT=$(cat 2>/dev/null || echo '{}')
CWD=$(printf '%s' "$INPUT" | jq -r '.cwd // empty' 2>/dev/null)
[ -z "$CWD" ] && CWD="$PWD"
[ -d "$CWD" ] || exit 0

# Пропускаем: домашнюю папку (там общий CLAUDE.md со списком сессий),
# корень, /tmp и системные каталоги.
case "$CWD" in
  "$HOME"|"/"|/tmp/*|/private/tmp/*|/var/*|/etc/*|/usr/*) exit 0 ;;
esac

MD="$CWD/CLAUDE.md"
[ -f "$MD" ] && exit 0

# Вверх по дереву: если CLAUDE.md есть у родителя — он и подхватится, свой не нужен.
p=$(dirname "$CWD")
while [ "$p" != "/" ] && [ "$p" != "$HOME" ]; do
  [ -f "$p/CLAUDE.md" ] && exit 0
  p=$(dirname "$p")
done

NAME=$(basename "$CWD")
TODAY=$(date "+%d.%m.%Y")

