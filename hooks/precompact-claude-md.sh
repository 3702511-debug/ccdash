#!/bin/bash
# PreCompact hook: перед сжатием контекста напоминает выгрузить важное в CLAUDE.md.
#
# Зачем: compact — главная точка потери контекста. Глобальное правило пользователя
# (~/.claude/CLAUDE.md) требует сохранять при сжатии все уникальные идентификаторы,
# найденные решения, конфигурации и открытые задачи. Но summary живёт внутри сессии,
# а сессия может быть удалена. CLAUDE.md — единственное, что переживает и compact,
# и удаление jsonl (инцидент 22.09.2026).
#
# Что делает: инжектит в контекст модели инструкцию обновить CLAUDE.md ДО сжатия.

set -uo pipefail

INPUT=$(cat 2>/dev/null || echo '{}')
CWD=$(printf '%s' "$INPUT" | jq -r '.cwd // empty' 2>/dev/null)
[ -z "$CWD" ] && CWD="$PWD"

# Ищем CLAUDE.md в cwd и выше по дереву
MD=""
p="$CWD"
while [ -n "$p" ] && [ "$p" != "/" ]; do
  if [ -f "$p/CLAUDE.md" ]; then MD="$p/CLAUDE.md"; break; fi
  [ "$p" = "$HOME" ] && break
  p=$(dirname "$p")
done
[ -z "$MD" ] && [ -f "$HOME/CLAUDE.md" ] && MD="$HOME/CLAUDE.md"
[ -z "$MD" ] && exit 0

CTX="ПЕРЕД СЖАТИЕМ: обнови базу знаний сессии — ${MD}

Контекст сейчас будет сжат. Всё, чего нет в файле, может быть потеряно: summary живёт внутри сессии, а сессию может удалить автоматическая чистка Claude Code.

Перенеси в файл то, что ещё не записано:
- уникальные идентификаторы: sid, IP, порты, домены, пути, имена файлов;
- найденные решения и причины багов: что пробовали, что не сработало, что заработало;
- конфигурации железа и сервисов: настройки, прошивки, протоколы, версии;
- открытые задачи: что делается сейчас, что ждёт пользователя, что заблокировано;
- фоновые процессы и артефакты на диске: где лежат бэкапы, дампы, логи.

Не дублируй то, что уже есть в файле. Не пиши туда секреты — для них ~/.claude/projects/<slug>/memory/ или .gitignore-нутый .env, в CLAUDE.md только указание места."

jq -n --arg ctx "$CTX" --arg md "$MD" '{
  systemMessage: ("Напоминание: обнови " + $md + " перед сжатием контекста"),
  hookSpecificOutput: { hookEventName: "PreCompact", additionalContext: $ctx }
}'
exit 0
